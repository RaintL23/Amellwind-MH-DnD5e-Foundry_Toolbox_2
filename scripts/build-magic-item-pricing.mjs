/**
 * Converts scripts/data/magic-item-pricing.csv →
 * src/features/dnd/shop-generator/data/magic-item-pricing.data.ts
 *
 * Update the CSV (replace the file), then run: pnpm pricing:build
 * Also runs automatically as part of `pnpm build`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const csvPath = path.resolve(__dirname, "data/magic-item-pricing.csv");
const outDir = path.resolve(
  __dirname,
  "../src/features/dnd/shop-generator/data",
);
const outPath = path.join(outDir, "magic-item-pricing.data.ts");

function parseCsvLine(line) {
  const cells = [];
  let current = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (inQuotes && line[i + 1] === '"') {
        current += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }
    if (ch === "," && !inQuotes) {
      cells.push(current);
      current = "";
      continue;
    }
    current += ch;
  }
  cells.push(current);
  return cells;
}

/** Same normalization used at runtime for lookups. */
export function normalizePricingName(name) {
  return name
    .trim()
    .toLowerCase()
    .replace(/['']/g, "'")
    .replace(/[–—]/g, "-")
    .replace(/,/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const raw = readFileSync(csvPath, "utf8").replace(/^\uFEFF/, "");
const lines = raw.split(/\r?\n/).filter((l) => l.trim().length > 0);
if (lines.length < 2) {
  console.error("magic-item-pricing.csv is empty or missing a header.");
  process.exit(1);
}

const header = parseCsvLine(lines[0]).map((h) => h.trim());
const nameIdx = header.findIndex((h) => h.toLowerCase() === "item name");
const costIdx = header.findIndex((h) => h.toLowerCase() === "cost (gp)");
const noteIdx = header.findIndex((h) => h.toLowerCase() === "note");
const sheetIdx = header.findIndex((h) => h.toLowerCase() === "source sheet");
if (nameIdx < 0 || costIdx < 0) {
  console.error(
    'CSV must include "Item Name" and "Cost (gp)" columns. Found:',
    header.slice(0, 10),
  );
  process.exit(1);
}

/** @type {Record<string, number>} */
const pricingByNormalizedName = {};
/** @type {Record<string, { canonicalName: string, note: string, sourceSheet: string }>} */
const pricingMetaByNormalizedName = {};
let priced = 0;
let skipped = 0;

for (let i = 1; i < lines.length; i++) {
  const cells = parseCsvLine(lines[i]);
  const name = (cells[nameIdx] ?? "").trim();
  const costRaw = (cells[costIdx] ?? "").trim().replace(/,/g, "");
  if (!name) continue;
  if (!/^\d+$/.test(costRaw)) {
    skipped++;
    continue;
  }
  const key = normalizePricingName(name);
  if (!key) continue;
  const cost = Number(costRaw);
  pricingByNormalizedName[key] = cost;
  const note = noteIdx >= 0 ? (cells[noteIdx] ?? "").trim() : "";
  const sourceSheet = sheetIdx >= 0 ? (cells[sheetIdx] ?? "").trim() : "";
  pricingMetaByNormalizedName[key] = {
    canonicalName: name,
    note,
    sourceSheet,
  };
  priced++;
}

mkdirSync(outDir, { recursive: true });

const banner = `/**
 * AUTO-GENERATED by scripts/build-magic-item-pricing.mjs — do not edit by hand.
 * Source: scripts/data/magic-item-pricing.csv
 * Regenerated: ${new Date().toISOString()}
 * Entries: ${priced} priced, ${skipped} skipped (non-numeric cost)
 */
`;

const body = `${banner}
export interface MagicItemPricingMeta {
  canonicalName: string;
  note: string;
  sourceSheet: string;
}

export const MAGIC_ITEM_PRICING_BY_NAME: Readonly<Record<string, number>> = ${JSON.stringify(
  pricingByNormalizedName,
  null,
  2,
)} as const;

export const MAGIC_ITEM_PRICING_META_BY_NAME: Readonly<
  Record<string, MagicItemPricingMeta>
> = ${JSON.stringify(pricingMetaByNormalizedName, null, 2)} as const;

export function normalizeMagicItemPricingName(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/['']/g, "'")
    .replace(/[–—]/g, "-")
    .replace(/,/g, " ")
    .replace(/\\s+/g, " ")
    .trim();
}

/** "+1 foo" ↔ "foo +1" for CSV names that put the bonus after the item name. */
export function magicItemPricingNameAliases(normalizedName: string): string[] {
  const aliases = [normalizedName];
  const prefix = normalizedName.match(/^(\\+[123])\\s+(.+)$/);
  if (prefix) {
    aliases.push(\`\${prefix[2]} \${prefix[1]}\`);
  }
  const suffix = normalizedName.match(/^(.+)\\s+(\\+[123])$/);
  if (suffix) {
    aliases.push(\`\${suffix[2]} \${suffix[1]}\`);
  }
  return [...new Set(aliases)];
}
`;

writeFileSync(outPath, body, "utf8");
console.log(
  `Wrote ${priced} pricing entries (${skipped} skipped) → ${path.relative(process.cwd(), outPath)}`,
);
